using TMPro;

namespace CloneSwarm.UI.P3R
{
    /// <summary>
    /// กฎการจัดตัวหนังสือที่ต้องใช้ร่วมกันทั้งเกม — มีที่เดียวเพื่อไม่ให้แต่ละจอตีความเอง
    ///
    /// **ปัญหาที่คลาสนี้เกิดมาแก้: letter-spacing ทำภาษาไทยพัง**
    /// design handoff สั่งให้ป้ายกำกับสไตล์ mono ถ่างระยะตัวอักษร `.16–.30em`
    /// ซึ่งสวยกับภาษาละติน แต่ภาษาไทยวางสระบน-ล่างและวรรณยุกต์เป็น **อักขระไม่มีความกว้าง**
    /// ที่ต้องซ้อนอยู่บนพยัญชนะตัวก่อนหน้า
    ///
    /// TMP เติมระยะหลังทุกกลิฟรวมทั้งพวกนี้ด้วย — `เพื่อ` จึงกลายเป็น `เพื ่อ`
    /// สระกับวรรณยุกต์หลุดลอยออกไปจากพยัญชนะ อ่านไม่ออกและดูเหมือนฟอนต์เสีย
    ///
    /// **กฎที่ใช้: ถ้าข้อความมีอักษรไทยแม้ตัวเดียว ไม่ถ่างระยะเลย**
    /// เข้มกว่าที่จำเป็นนิดหน่อย (ตัดเฉพาะอักขระซ้อนก็พอในทางทฤษฎี) แต่เลือกทางนี้เพราะ
    /// การถ่างระยะตัวอักษรไม่ใช่ธรรมเนียมของการเรียงพิมพ์ไทยอยู่แล้ว — ถ่างไปก็ไม่ได้สวยขึ้น
    ///
    /// **ข้อแลก:** ข้อความผสมอย่าง `ESC เพื่อกลับเข้าเกม` จะเสียการถ่างของ `ESC` ไปด้วย
    /// ถ้าอยากได้ทั้งสองอย่างต้องแยกเป็น TMP สองตัว — ยังไม่คุ้มกับความยุ่งตอนนี้
    /// </summary>
    public static class P3RText
    {
        /// <summary>ช่วง Unicode ของอักษรไทยทั้งบล็อก</summary>
        public static bool HasThai(string s)
        {
            if (string.IsNullOrEmpty(s)) return false;
            foreach (char c in s)
                if (c >= '฀' && c <= '๿') return true;
            return false;
        }

        /// <summary>
        /// ตั้งระยะห่างตัวอักษรอย่างปลอดภัย — ข้อความไทยได้ 0 เสมอ
        /// ใช้แทนการเขียน <c>tmp.characterSpacing = x</c> ตรงๆ ทุกที่
        /// </summary>
        public static void SetTracking(TMP_Text t, float spacing)
        {
            if (t == null) return;
            t.characterSpacing = HasThai(t.text) ? 0f : spacing;
        }

        /// <summary>
        /// ตั้งข้อความแล้วตั้งระยะห่างให้ถูกในคราวเดียว — ใช้ตอนข้อความเปลี่ยนได้ตอนรัน
        /// (ถ้าเปลี่ยนข้อความอย่างเดียวโดยไม่เรียกอันนี้ ระยะเดิมจะค้างแล้วไทยพังอีก)
        /// </summary>
        public static void SetTextAndTracking(TMP_Text t, string text, float spacing)
        {
            if (t == null) return;
            t.text = text;
            SetTracking(t, spacing);
        }

        /// <summary>
        /// ตัวพิมพ์ใหญ่แบบปลอดภัย — ไทยไม่มีตัวพิมพ์ใหญ่ การบังคับจึงไม่มีผลกับไทย
        /// แต่ทำให้ลุค ALL-CAPS ของแบบหายไปเงียบๆ เมื่อสลับภาษา · คืนค่าว่าได้ผลจริงไหม
        /// เพื่อให้จุดที่เรียกตัดสินใจต่อได้ว่าจะเปลี่ยนน้ำหนัก/ขนาดชดเชยหรือไม่
        /// </summary>
        public static bool TryUpperCase(TMP_Text t)
        {
            if (t == null || HasThai(t.text)) return false;
            t.fontStyle |= FontStyles.UpperCase;
            return true;
        }
    }
}
